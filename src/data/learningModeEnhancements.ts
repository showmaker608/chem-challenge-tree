export function withCompleteJuniorLearningModes(chapters: Chapter[]): Chapter[] {
  return chapters.map((chapter) => ({
    ...chapter,
    sections: chapter.sections.map((section) => ({
      ...section,
      nodes: section.nodes.map((node) => {
        if (node.learningContent) return node;
        const content = missingLearningContent[node.id];
        const example = node.bigQuestion?.subQuestions[0] ?? node.challenges[0];
        if (!content || !example) return node;
        return {
          ...node,
          learningContent: { ...content, example },
        };
      }),
    })),
  }));
}
